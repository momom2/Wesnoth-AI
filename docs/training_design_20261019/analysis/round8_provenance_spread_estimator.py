"""Round 8, provenance stance: a shape-free estimator of the in-span spread v, and what a null says.

The design reads "v-hat from S1's progressive fits" without naming an estimator, and states what a
null means through the Gaussian model (floor sd 0.0016 at mu 0). Here:

Estimator. Batches are independent (different games). Fit OLS of the labels on [typed terms, x] in
each batch k (the per-batch Gram matrix and X'T the design already logs): w_k = w + e_k, E[e_k] = 0,
Cov(e_k) = C_k. With S the within-type covariance of x (a function of features only),
    v-hat = mean over pairs j < k of  w_j' S w_k
is unbiased for v = w' S w, the variance of the best linear in-span predictor of the advantage,
for ANY distribution of advantages and features (only independence across batches is used).
Its variance is 4 s2 v / N + 2 tr((S C)^2) / (K (K - 1)), with tr((S C)^2) about d (s2 / n)^2 for
n labels a batch, N = K n, s2 the label second moment. Nearest prior work: the pairwise
estimator of explainable variance of Kong & Valiant (NeurIPS 2018), and Dicker (Biometrika 2014).

Scarf's bound. For any distribution with mean m and variance v, E[(m + r)+] <= (m + sqrt(m^2 + v)) / 2,
and the bound is attained by a two-point law. So an upper confidence bound on v caps the gain of the
oracle in-span switch rule, shape-free.

Part 1 checks the estimator by simulation (d = 30, K = 8, 10,000 labels a batch, 60 runs, labels generated by the coin mechanism at
P = 0.25 with z = +-1, four feature laws, an off-span component). Part 2 states its SE and the
null's shape-free meaning at the design's scale. numpy and the standard library only.
"""
import math

import numpy as np

RNG = np.random.default_rng(20261020)
P = 0.25
ELO = 800 / math.log(10)
BAND = 76.1                      # band decisions per side-game (round5_synthesis_power.py, parity3 share x own1 unit)
N_BATCH = 2 * BAND * 100_000     # labels a batch, both sides


def features(law, n, d, L):
    if law == "gaussian":
        zf = RNG.normal(size=(n, d))
    elif law == "skewed":
        zf = RNG.exponential(size=(n, d)) - 1.0
    elif law == "t3":
        zf = RNG.standard_t(3, size=(n, d)) / math.sqrt(3.0)
    elif law == "sparse":
        zf = (RNG.random((n, d)) < 0.05) / math.sqrt(0.05 * 0.95) - 0.05 / math.sqrt(0.05 * 0.95)
    return zf @ L.T


def coin_labels(adv, m0=0.02):
    d_coin = (RNG.random(adv.shape) < P).astype(float)
    p_win = (1 + m0 + d_coin * adv) / 2
    z = np.where(RNG.random(adv.shape) < p_win, 1.0, -1.0)
    return (d_coin - P) / (P * (1 - P)) * z


def ols(x, t):
    xa = np.column_stack([np.ones(len(x)), x])
    return np.linalg.solve(xa.T @ xa, xa.T @ t)[1:]


def simulate(law, d=30, k_batches=8, n=10_000, reps=60, v_target=2e-3, off_span_sd=0.02):
    L = np.eye(d) * 0.8 + RNG.normal(size=(d, d)) * 0.2 / math.sqrt(d)
    sigma = L @ L.T
    w = RNG.normal(size=d)
    w *= math.sqrt(v_target / (w @ sigma @ w))
    est, plug = [], []
    for _ in range(reps):
        ws, xs = [], []
        for _ in range(k_batches):
            x = features(law, n, d, L)
            off = RNG.choice([-1.0, 4.0], size=n, p=[0.8, 0.2]) * off_span_sd / 2.0   # mean 0, skewed, not in span
            adv = -0.005 + x @ w + off
            t = coin_labels(adv)
            ws.append(ols(x, t))
            xs.append(x)
        xall = np.vstack(xs)
        s_hat = np.cov(xall.T)
        pairs = [ws[j] @ s_hat @ ws[k] for j in range(k_batches) for k in range(j + 1, k_batches)]
        est.append(np.mean(pairs))
        w_pool = np.mean(ws, axis=0)
        plug.append(w_pool @ s_hat @ w_pool)
    s2 = 1 / (P * (1 - P))
    n_all = k_batches * n
    se_formula = math.sqrt(4 * s2 * v_target / n_all + 2 * d * (s2 / n) ** 2 / (k_batches * (k_batches - 1)))
    est = np.array(est)
    print(f"  {law:8s}: true v {v_target:.2e}; v-hat mean {est.mean():.3e} +- {est.std() / math.sqrt(reps):.1e} "
          f"(bias {est.mean() / v_target - 1:+.3f}); SE per run {est.std():.2e} against formula {se_formula:.2e}; "
          f"naive pooled plug-in {np.mean(plug):.3e}")


def design_scale():
    print("\n2. the estimator at the design's scale (d 772 within types; labels a batch 15.22 M)")
    d = 772
    for s2, label in ((3.67, "measured transfer"), (4.48, "batch-1 columns only"), (1 / (P * (1 - P)), "exact ceiling, no variates")):
        for k in (2, 3, 8):
            n = N_BATCH if k > 2 else N_BATCH / 2       # k = 2: batch 1 split in halves by game
            kk = k if k > 2 else 2
            se0 = math.sqrt(2 * d * (s2 / n) ** 2 / (kk * (kk - 1)))
            v_up = 2 * se0
            oracle = (0.0 + math.sqrt(v_up)) / 2
            reading = "batch 1 halves" if k == 2 else f"{k} batches"
            print(f"  s2 {s2:.2f} ({label}), {reading}: SE(v-hat) at v = 0 {se0:.2e}; a null bounds v <= {v_up:.2e} "
                  f"(sd {math.sqrt(v_up):.4f}); Scarf cap on the oracle in-span gain at m 0: "
                  f"{ELO * BAND * oracle:.1f} Elo (Gaussian oracle at that sd {ELO * BAND * math.sqrt(v_up) * 0.3989:.1f})")
    print("\n  Scarf cap per band decision, (m + sqrt(m^2 + v)) / 2, at v = 2.53e-6 (8 batches, s2 3.67):")
    for m in (0.0, -0.001, -0.002, -0.004, -0.006):
        cap = (m + math.sqrt(m * m + 2.53e-6)) / 2
        print(f"    typed mean m {m:+.4f}: {cap:.2e} per decision = {ELO * BAND * cap:.1f} Elo if the whole band had that mean")


def main():
    print("1. simulation check (d 30, 8 batches of 10,000 labels, 60 runs per law, coin labels at P 0.25, z = +-1, typed mean -0.005,"
          " a skewed off-span part of sd 0.02)")
    for law in ("gaussian", "skewed", "t3", "sparse"):
        simulate(law)
    design_scale()


if __name__ == "__main__":
    main()
